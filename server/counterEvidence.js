// 지목이 무엇에 기대고 있는지 가린다 — 반박인가, 못 찾은 것인가.
//
// 유메가 낼 수 있는 가장 비싼 오류는 맞는 사실을 "사실과 다름"이라고 부르는 것이다.
// 사용자는 멀쩡한 정보를 버리고, 근거까지 달려 있어 알아차리기도 어렵다.
//
// 그 오류는 거의 한 가지 모양으로 온다. **검색에 안 나온다는 것을 틀렸다는 뜻으로 읽는 것.**
// 실제로 있었던 일 —
//
//   Wine Enthusiast가 어떤 와인에 88점을 줬다는 주장에 유메가 "사실과 다름"을 붙였다.
//   그런데 그 점수는 실재했다. 와인 평점은 구독자 전용 데이터베이스와 잡지 지면에
//   들어 있어 일반 웹검색에 잘 걸리지 않을 뿐이었다. 검색이 빈손이었던 것을
//   "그런 평점은 없다"로 옮겨 적은 것이다.
//
// 기록이 없다는 것을 판정으로 쓸 수 있는 경로는 이미 따로 있다 — 부존재 신뢰도(NEC)다.
// 거기서는 "어느 공간을 얼마나 덮었나"를 수치로 재고 임계값을 넘을 때만 판정한다.
// 반면 웹·리서치 단계에서 나온 "못 찾았다"는 그냥 못 찾은 것이다. 판정이 아니다.
//
// 그래서 여기서는 설명문이 어느 쪽인지만 가린다. 판정을 바꾸는 일은 claimGuard가 한다.

// 못 찾았다는 말. 이 표현들은 주장의 참·거짓에 대해 아무것도 말하지 않는다.
const ABSENCE = [
  /찾(을|아볼)\s*수\s*없/,
  /찾지\s*(못|않)/,
  /확인(할\s*수\s*없|되지\s*않|이\s*되지\s*않|\s*불가|되지\s*못)/,
  /검색\s*(결과\s*)?(에(서)?\s*)?(나오지\s*않|잡히지\s*않|없|되지\s*않|안\s*나)/,
  /(기록|자료|근거|출처|정보|리뷰|평점|언급|흔적|내용)(이|을|은|가|를)?\s*(전혀\s*)?(없|찾)/,
  /(나타나지|발견되지|검색되지|등장하지|보이지)\s*않/,
  /존재하지\s*않는\s*것으로\s*(보|판단|추정)/,
  /어디(에서)?도\s*(없|찾)/,
];

// 반박하는 말. 반박은 반드시 "그럼 실제로는 무엇인가"를 댄다 — 다른 수치, 다른 연도,
// 다른 주체. 그 대안이 문장에 있어야 지목이 근거를 가진 것이다.
const CONTRADICTION = [
  /실제(로는|는)|실제\s*(값|수치|연도|해|날짜|금액|가격|점수|평점|등급|주체|기관|명칭|이름|수상|발표|내용|기록|결과|수치는)/,
  /정확(히|하게)(는)?\s/,
  // 한글은 음절로 뭉치므로 '아닙니다'에는 '아니'가 없다. 활용형을 늘어놓는다.
  /아니(라|고|며|다|었|야)|아닙니다|아니에요|아님|아닌\s/,
  /(으|이)?로\s*(확인|기재|표기|나와|되어\s*있|명시)/,
  /(와|과)\s*다르게/,
  /상충|모순|배치된다|반대로\s*나/,
  /(이|가)\s*맞습니다|(이|가)\s*맞다/,
];

const has = (list, text) => list.some((re) => re.test(text));

/**
 * 설명문이 어디에 기대고 있는지.
 *   "contradiction" — 다른 값을 대고 있다. 지목이 근거를 가진 모양이다.
 *   "absence"       — 못 찾았다고만 말한다. 이건 판정이 아니다.
 *   "unclear"       — 둘 다 아니다. 판정을 흔들 만한 근거는 못 되지만 단정할 근거도 없다.
 *
 * 둘이 함께 있으면 반박으로 본다. "A에는 없고 실제로는 B다"는 반박이다.
 */
export function accusationGrounds(explanation) {
  const t = String(explanation || "").trim();
  if (!t) return "unclear";
  if (has(CONTRADICTION, t)) return "contradiction";
  if (has(ABSENCE, t)) return "absence";
  return "unclear";
}

/** 지목이 '못 찾음'에만 기대고 있는가. */
export function restsOnAbsence(explanation) {
  return accusationGrounds(explanation) === "absence";
}
