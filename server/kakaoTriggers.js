// 카톡에서 온 말 한 마디를 검증으로 보낼지 가리는 판단.
//
// 예전에는 "검증해줘"라고 말해야만 검증이 돌았다. 그런데 사람이 실제로 쓰는 말은
// "로또 1등 당첨금이 평균 20억이라는데 사실이야?" 쪽이다. 검증해 달라고 부탁하는 것이
// 아니라 그냥 묻는 것이고, 이 말투를 못 받으면 잡담 답변만 돌아간다.
//
// 넓히는 데는 값이 든다 — 잘못 걸리면 잡담 한 마디에 무료 확인 1회가 나간다.
// 그래서 세 가지를 함께 요구한다.
//
//   ① 진위를 묻는 말끝     — "사실이야", "진짜야", "맞나요", "정말인가요"
//   ② 물음표 또는 전언 표시 — "?" 또는 "~라는데 / ~라던데"
//   ③ 확인할 내용이 들어갈 만한 길이
//
// "맞아?" "진짜?" 같은 맞장구는 ③에서 걸러진다. 물음표를 선택으로 둔 이유는 카톡에서
// 자주 생략되기 때문인데, 대신 그때는 전언 표시("~라는데")가 있어야 한다.
//
// DB나 외부 호출을 물고 오지 않도록 웹훅에서 떼어 두었다. 이 판단만 따로, 빠르게
// 테스트할 수 있어야 한다 — 받아야 할 것과 받으면 안 되는 것이 둘 다 값을 가진 규칙이다.

/** 부탁하는 말투 — "이거 검증해줘", "팩트체크 좀". */
export const VERIFY_TRIGGER = /검증|팩트\s*체크/;

// "진짜야"와 "사실이야"는 받침 유무로 조사가 갈린다(진짜+야 / 사실+이야). 둘 다 받는다.
const ASK_ENDING = /(사실|진짜|정말)(이?야|이?니|인가요?|이?에요|예요|임|인지)?\s*[?？]*\s*$|맞(아|나요?|는지|습니까|죠)\s*[?？]*\s*$/u;
const ASK_MARK = /[?？]\s*$|라는데|라던데|다는데|다던데|라고\s*하던데|한다는데/u;
const ASK_MIN_CHARS = 12;

/** 그냥 묻는 말투 — "○○라는데 사실이야?". */
export function asksIfTrue(raw) {
  const text = String(raw || "").trim();
  return text.length >= ASK_MIN_CHARS && ASK_ENDING.test(text) && ASK_MARK.test(text);
}
