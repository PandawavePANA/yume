// 카톡에서 "그냥 물어본 것"을 검증으로 보내는 판단.
//
// 예전에는 "검증해줘"라고 말해야만 검증이 돌았다. 사람이 실제로 쓰는 말은
// "로또 1등 당첨금이 평균 20억이라는데 사실이야?" 쪽인데, 그 말투는 잡담으로 빠졌다.
//
// 넓히는 데는 값이 든다 — 잘못 걸리면 잡담 한 마디에 무료 확인 1회가 나간다.
// 그래서 받아야 할 것과 받으면 안 되는 것을 둘 다 못 박아 둔다.
import test from "node:test";
import assert from "node:assert/strict";
import { asksIfTrue } from "../kakaoTriggers.js";

test("진위를 묻는 말은 검증으로 보낸다", () => {
  const asks = [
    "로또 1등 당첨금이 평균 20억이라는데 사실이야?",
    "아스피린이 암을 예방한다던데 진짜야?",
    "민법 750조가 계약 해제 조항 맞나요?",
    "2023년 합계출산율이 0.72명이라는데 정말인가요?",
    "전세보증금은 무조건 집주인이 다 돌려줘야 한다던데 사실임?",
    "커피를 하루 세 잔 마시면 수명이 늘어난다는데 맞는지?",
    // 물음표가 없어도 전언 표시가 있으면 받는다. 카톡에서 물음표는 자주 생략된다.
    "비타민C 하루 10g이 감기를 막아준다던데 사실이야",
  ];
  for (const t of asks) assert.equal(asksIfTrue(t), true, t);
});

test("맞장구와 잡담은 검증으로 보내지 않는다", () => {
  // 하나 걸릴 때마다 무료 확인 1회가 그냥 나간다.
  const chats = [
    "맞아?",
    "진짜?",
    "사실이야?",
    "ㅋㅋㅋ 진짜야?",
    "안녕하세요",
    "오늘 날씨 어때?",
    "유메가 뭐하는 서비스야?",
    "고마워 잘 쓸게",
    "그거 어떻게 하는 거야?",
    "",
  ];
  for (const t of chats) assert.equal(asksIfTrue(t), false, t);
});

test("'검증해줘' 경로는 그대로 남아 있다", () => {
  // 이 말투는 VERIFY_TRIGGER가 잡는다. 여기서 false인 것이 정상이다.
  assert.equal(asksIfTrue("[뉴스 본문 어쩌고저쩌고] 검증해줘"), false);
});
